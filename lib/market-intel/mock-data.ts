function mkTrend(base: number, growth: number, seed: number): { day: string; revenue: number }[] {
  // 14-day deterministic-ish trend ending today
  const days: { day: string; revenue: number }[] = [];
  let rng = seed;
  const rnd = () => {
    rng |= 0;
    rng = (rng + 0x6d2b79f5) | 0;
    let t = Math.imul(rng ^ (rng >>> 15), 1 | rng);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  let v = base;
  for (let i = 13; i >= 0; i--) {
    v = v * (1 + growth / 14 + (rnd() - 0.5) * 0.1);
    const d = new Date();
    d.setDate(d.getDate() - i);
    days.push({ day: d.toISOString().slice(0, 10), revenue: Math.round(v) });
  }
  return days;
}

